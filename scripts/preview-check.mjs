import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
const response=await page.goto('http://127.0.0.1:3002/',{waitUntil:'networkidle'});
await page.screenshot({path:'output/qa/home-desktop.png',fullPage:true});
console.log(JSON.stringify({status:response.status(),errors,video:await page.locator('video').evaluate(v=>({ready:v.readyState,paused:v.paused,duration:v.duration})),overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}));
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'output/qa/home-mobile.png',fullPage:true});
console.log(JSON.stringify({mobileOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}));
await browser.close();
